"""Turn the supersampled renders in tools/raw/ into game sprite sheets.

Each render is scaled down to its final size, its alpha is made hard, its colours are
reduced to a small palette and it gets a one-pixel dark outline: the look of
pre-rendered 16-bit era sprites. Car poses are packed into one sheet per car
(9 turn poses across, normal and braking rows down). Writes drift2/assets/*.png and
drift2/assets/manifest.js.

Usage: python3 pixelate.py
"""
import json
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, 'raw')
OUT = os.path.join(HERE, '..', 'assets')
OUTLINE = (20, 16, 28, 255)
CAR_COLOURS = 40
SCENERY_COLOURS = 32


def shrink(img, ss):
    """Area-average downscale with premultiplied alpha, then a hard alpha edge."""
    w, h = max(1, round(img.width / ss)), max(1, round(img.height / ss))
    small = img.convert('RGBa').resize((w, h), Image.Resampling.BOX).convert('RGBA')
    px = small.load()
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            px[x, y] = (r, g, b, 255) if a >= 100 else (0, 0, 0, 0)
    return small


def posterize(img, colours):
    """Reduce opaque pixels to a shared palette, keeping transparency."""
    alpha = img.getchannel('A')
    rgb = Image.new('RGB', img.size, (0, 0, 0))
    rgb.paste(img.convert('RGB'), mask=alpha)
    q = rgb.quantize(colors=colours, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert('RGB')
    out = q.convert('RGBA')
    out.putalpha(alpha)
    return out


def outline(img):
    w, h = img.size
    src = img.load()
    out = img.copy()
    dst = out.load()
    for y in range(h):
        for x in range(w):
            if src[x, y][3]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < w and 0 <= ny < h and src[nx, ny][3]:
                    dst[x, y] = OUTLINE
                    break
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    index = json.load(open(os.path.join(RAW, 'index.json')))
    groups = {}
    for name, meta in index.items():
        groups.setdefault(meta['group'], []).append((name, meta))

    manifest = {'cars': {}, 'scenery': {}}
    for group, items in sorted(groups.items()):
        meta0 = items[0][1]
        ss, ppm = meta0['ss'], meta0['pxPerM']
        if meta0['kind'] == 'car':
            frames = {}
            for name, meta in items:
                row, col = map(int, name.split('__')[1].split('_'))
                img = shrink(Image.open(os.path.join(RAW, name + '.png')), ss)
                ax, ay = meta['anchor'][0] / ss, meta['anchor'][1] / ss
                frames[(row, col)] = (img, ax, ay)
            left = max(ax for _, ax, _ in frames.values())
            right = max(img.width - ax for img, ax, _ in frames.values())
            top = max(ay for _, _, ay in frames.values())
            bottom = max(img.height - ay for img, _, ay in frames.values())
            fw, fh = int(left + right) + 3, int(top + bottom) + 3
            fax, fay = round(left) + 1, round(top) + 1
            rows = 1 + max(r for r, _ in frames)
            cols = 1 + max(c for _, c in frames)
            sheet = Image.new('RGBA', (fw * cols, fh * rows), (0, 0, 0, 0))
            for (row, col), (img, ax, ay) in frames.items():
                sheet.paste(img, (col * fw + fax - round(ax), row * fh + fay - round(ay)))
            sheet = posterize(sheet, CAR_COLOURS)
            framed = Image.new('RGBA', sheet.size, (0, 0, 0, 0))
            for row in range(rows):
                for col in range(cols):
                    box = (col * fw, row * fh, (col + 1) * fw, (row + 1) * fh)
                    framed.paste(outline(sheet.crop(box)), box[:2])
            framed.save(os.path.join(OUT, group + '.png'), optimize=True)
            manifest['cars'][group] = {'file': group + '.png', 'fw': fw, 'fh': fh, 'ax': fax, 'ay': fay,
                                       'cols': cols, 'rows': rows, 'pxPerM': ppm}
        else:
            name, meta = items[0]
            img = shrink(Image.open(os.path.join(RAW, name + '.png')), ss)
            pad = Image.new('RGBA', (img.width + 2, img.height + 2), (0, 0, 0, 0))
            pad.paste(img, (1, 1))
            img = outline(posterize(pad, SCENERY_COLOURS))
            img.save(os.path.join(OUT, group + '.png'), optimize=True)
            manifest['scenery'][group] = {'file': group + '.png', 'w': img.width, 'h': img.height,
                                          'ax': round(meta['anchor'][0] / ss) + 1, 'ay': round(meta['anchor'][1] / ss) + 1,
                                          'pxPerM': ppm}

    with open(os.path.join(OUT, 'manifest.js'), 'w') as f:
        f.write('// Generated by tools/pixelate.py. Sprite sheet layout and anchors.\n')
        f.write('window.DRIFT_SPRITES = ' + json.dumps(manifest, indent=1) + ';\n')
    print(f"{len(manifest['cars'])} car sheets, {len(manifest['scenery'])} scenery sprites")


if __name__ == '__main__':
    main()
